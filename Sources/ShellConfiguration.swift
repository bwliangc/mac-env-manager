import Foundation

enum ShellConfiguration {
    static let markerStart = "# >>> MacEnvManager >>>"
    static let markerEnd = "# <<< MacEnvManager <<<"

    static let sourceBlock = """
    \(markerStart)
    if [ -r "$HOME/Library/Application Support/MacEnvManager/environment.zsh" ]; then
      . "$HOME/Library/Application Support/MacEnvManager/environment.zsh"
    fi
    \(markerEnd)
    """

    static let cshSourceBlock = """
    \(markerStart)
    if ( -r "$HOME/Library/Application Support/MacEnvManager/environment.csh" ) then
      source "$HOME/Library/Application Support/MacEnvManager/environment.csh"
    endif
    \(markerEnd)
    """

    static let posixStartupFile = """
    # Generated by MacEnvManager: preserve the user's interactive startup file.
    if [ -n "${_MAC_ENV_MANAGER_ORIGINAL_ENV:-}" ]; then
      if [ "$_MAC_ENV_MANAGER_ORIGINAL_ENV" != "$ENV" ] && [ -r "$_MAC_ENV_MANAGER_ORIGINAL_ENV" ]; then
        . "$_MAC_ENV_MANAGER_ORIGINAL_ENV"
      fi
    elif [ -n "${KSH_VERSION:-}" ]; then
      if [ -r "$HOME/.kshrc" ]; then . "$HOME/.kshrc"; fi
    else
      if [ -r "$HOME/.shrc" ]; then . "$HOME/.shrc"; fi
    fi
    . "$HOME/Library/Application Support/MacEnvManager/environment.zsh"
    """ + "\n"

    private static let protectedNames: Set<String> = [
        "HOME", "PATH", "PWD", "OLDPWD", "SHELL", "SHLVL",
        "USER", "LOGNAME", "ZDOTDIR", "ENV", "BASH_ENV", "_"
    ]

    static func validateVariable(name: String, value: String) throws {
        let pattern = "^[A-Za-z_][A-Za-z0-9_]*$"
        guard name.range(of: pattern, options: .regularExpression) != nil else {
            throw EnvironmentManagerError.invalidName
        }
        guard !protectedNames.contains(name), !name.hasPrefix("_MAC_ENV_MANAGER_") else {
            throw EnvironmentManagerError.protectedName(name)
        }
        guard !value.contains("\n"), !value.contains("\r"), !value.contains("\0") else {
            throw EnvironmentManagerError.invalidValue
        }
    }

    static func shellQuote(_ value: String) -> String {
        "'" + value.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    static func renderEnvironmentFile(
        variables: [ManagedVariable]
    ) -> String {
        var lines = [
            "# Generated by MacEnvManager. Changes made here may be overwritten.",
            "# File permissions are restricted to the current user.",
            ""
        ]

        for variable in variables.sorted(by: { $0.name < $1.name }) {
            lines.append(variable.isEnabled
                ? "export \(variable.name)=\(shellQuote(variable.value))"
                : "unset \(variable.name)")
        }

        lines.append("""

        if [ "${ENV:-}" != "$HOME/Library/Application Support/MacEnvManager/posix-init.sh" ]; then
          if [ -n "${ENV:-}" ]; then
            export _MAC_ENV_MANAGER_ORIGINAL_ENV="$ENV"
          fi
          export ENV="$HOME/Library/Application Support/MacEnvManager/posix-init.sh"
        fi
        """)

        return lines.joined(separator: "\n") + "\n"
    }

    // Decode data rather than interpolate C-shell literals: history expansion (!)
    // and quoting rules differ from POSIX shells, including inside single quotes.
    private static func cshValue(_ value: String) -> String {
        let encoded = Data(value.utf8).base64EncodedString()
        return "\"`/usr/bin/printf '%s' '\(encoded)' | /usr/bin/base64 -D`\""
    }

    static func renderCshEnvironmentFile(
        variables: [ManagedVariable]
    ) -> String {
        var lines = ["# Generated by MacEnvManager. Values are encoded for C-shell quoting, not encrypted."]
        for variable in variables.sorted(by: { $0.name < $1.name }) {
            lines.append(variable.isEnabled
                ? "setenv \(variable.name) \(cshValue(variable.value))"
                : "unsetenv \(variable.name)")
        }
        lines.append("""
        if ( ! $?ENV ) setenv ENV ""
        if ( "$ENV" != "$HOME/Library/Application Support/MacEnvManager/posix-init.sh" ) then
          if ( "$ENV" != "" ) setenv _MAC_ENV_MANAGER_ORIGINAL_ENV "$ENV"
          setenv ENV "$HOME/Library/Application Support/MacEnvManager/posix-init.sh"
        endif
        """)
        return lines.joined(separator: "\n") + "\n"
    }

    static func installManagedBlock(in profile: String, filename: String) throws -> String {
        let cleaned = try removeManagedBlock(from: profile, filename: filename)
        let base = cleaned.trimmingCharacters(in: .newlines)
        let sourceBlock = [".cshrc", ".tcshrc", ".login"].contains(filename) ? cshSourceBlock : self.sourceBlock
        if base.isEmpty {
            return sourceBlock + "\n"
        }
        return base + "\n\n" + sourceBlock + "\n"
    }

    static func removeManagedBlock(from profile: String, filename: String) throws -> String {
        let lines = profile.components(separatedBy: "\n")
        var output: [String] = []
        var insideBlock = false
        var sawStart = false

        for line in lines {
            if line == markerStart {
                guard !insideBlock else {
                    throw EnvironmentManagerError.malformedProfile(filename)
                }
                insideBlock = true
                sawStart = true
                continue
            }

            if line == markerEnd {
                guard insideBlock else {
                    throw EnvironmentManagerError.malformedProfile(filename)
                }
                insideBlock = false
                continue
            }

            if !insideBlock {
                output.append(line)
            }
        }

        if insideBlock || (!sawStart && profile.contains(markerEnd)) {
            throw EnvironmentManagerError.malformedProfile(filename)
        }

        while output.last == "" {
            output.removeLast()
        }
        return output.joined(separator: "\n")
    }

    static func unmanagedDefinitionLines(for name: String, in profile: String) -> [Int] {
        guard let cleaned = try? removeManagedBlock(from: profile, filename: "profile") else {
            return []
        }
        let escaped = NSRegularExpression.escapedPattern(for: name)
        let pattern = "^\\s*(?:(?:export\\s+)?" + escaped + "\\s*=|setenv\\s+" + escaped + "(?:\\s|$))"
        guard let expression = try? NSRegularExpression(pattern: pattern) else {
            return []
        }

        return cleaned.components(separatedBy: "\n").enumerated().compactMap { index, line in
            let range = NSRange(line.startIndex..<line.endIndex, in: line)
            return expression.firstMatch(in: line, range: range) == nil ? nil : index + 1
        }
    }
}
